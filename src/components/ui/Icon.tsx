export interface IconProps extends Omit<LucideProps, 'size'> {
  icon?: LucideIcon;
  name?: string;
  size?: 16 | 20 | 24 | number;
  strokeWidth?: number;
  className?: string;
  title?: string;
  'aria-hidden'?: boolean | 'true' | 'false';
  'aria-label'?: string;
}

export function Icon({
  icon,
  name,
  size = 20,
  strokeWidth = 1.75,
  className = '',
  'aria-hidden': ariaHidden,
  'aria-label': ariaLabel,
  children,
  ...props
}: IconProps & { children?: React.ReactNode }) {
  // If children is a string (e.g. <Icon>school</Icon> or <Icon>{icon}</Icon>), treat as name
  const rawName = name || (typeof children === 'string' ? children.trim() : undefined);
  const ResolvedIcon =
    icon ||
    (rawName ? ICON_NAME_MAP[rawName.toLowerCase()] || ICON_NAME_MAP[rawName.toLowerCase().replace(/_/g, '-')] : undefined) ||
    HelpCircle;

  const isAriaHidden = ariaHidden !== undefined ? ariaHidden : ariaLabel ? undefined : true;

  return (
    <ResolvedIcon
      size={size}
      strokeWidth={strokeWidth}
      className={className}
      aria-hidden={isAriaHidden}
      aria-label={ariaLabel}
      {...props}
    />
  );
}

export default Icon;
